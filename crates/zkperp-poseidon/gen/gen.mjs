// Emits circomlib Poseidon constants (t = 2, 3, 5) as Rust, plus test vectors
// from circomlibjs' own buildPoseidon (the optimized implementation).
import { buildPoseidon } from "circomlibjs";
import consts from "./node_modules/circomlibjs/src/poseidon_constants.js";
import fs from "fs";

const [outConsts, outVectors] = process.argv.slice(2);
const RP = [56, 57, 56, 60, 60, 63, 64, 63, 60, 66, 60, 65, 70, 60, 64, 68];
const hex = (h) => h.replace(/^0x/, "").padStart(64, "0");
const bytes = (h) => "[" + hex(h).match(/../g).map((b) => "0x" + b).join(",") + "]";

let rs = "// @generated by gen.mjs from circomlibjs 0.1.7 poseidon_constants.js. Do not edit.\n";
rs += "// Field elements are 32-byte big-endian.\n\n";
for (const t of [2, 3, 5]) {
  const C = consts.C[t - 2], M = consts.M[t - 2];
  rs += `pub const ROUNDS_P_T${t}: u32 = ${RP[t - 2]};\n`;
  rs += `pub const C_T${t}: [[u8; 32]; ${C.length}] = [\n${C.map((c) => "    " + bytes(c) + ",").join("\n")}\n];\n`;
  rs += `pub const M_T${t}: [[[u8; 32]; ${t}]; ${t}] = [\n${M.map((row) => "    [" + row.map(bytes).join(", ") + "],").join("\n")}\n];\n\n`;
}
// Empty-subtree hashes for a depth-20 Poseidon(2) Merkle tree with zero leaves.
const depth = 20;
const p2 = await buildPoseidon();
let z = 0n;
const zeros = [z];
for (let i = 0; i < depth; i++) {
  z = p2.F.toObject(p2([z, z]));
  zeros.push(z);
}
rs += `pub const TREE_DEPTH: u32 = ${depth};\n`;
rs += `/// zeros[i] = root of an empty subtree of height i (zeros[0] = empty leaf = 0).\n`;
rs += `pub const ZEROS: [[u8; 32]; ${depth + 1}] = [\n${zeros.map((x) => "    " + bytes(x.toString(16)) + ",").join("\n")}\n];\n`;
fs.writeFileSync(outConsts, rs);

const poseidon = await buildPoseidon();
const F = poseidon.F;
const big = (s) => BigInt(s);
const r = big("21888242871839275222246405745257275088548364400416034343698204186575808495617");
const inputsList = [
  [1n], [0n], [r - 1n],
  [1n, 2n], [0n, 0n], [r - 1n, r - 2n], [123456789n, 987654321n],
  [1n, 2n, 3n, 4n], [r - 1n, 0n, 42n, 2n ** 200n],
];
const vectors = inputsList.map((inp) => ({
  inputs: inp.map((x) => x.toString(16).padStart(64, "0")),
  output: F.toObject(poseidon(inp)).toString(16).padStart(64, "0"),
}));
function treeRoot(leaves) {
  let level = leaves.slice();
  for (let i = 0; i < depth; i++) {
    const next = [];
    for (let j = 0; j < Math.max(1, Math.ceil(level.length / 2)); j++) {
      const l = level[2 * j] ?? zeros[i], r = level[2 * j + 1] ?? zeros[i];
      next.push(F.toObject(poseidon([l, r])));
    }
    level = next;
  }
  return level[0];
}
const leaves = [1n, 2n, 3n];
const merkle = leaves.map((_, k) => ({
  leaves: leaves.slice(0, k + 1).map((x) => x.toString(16).padStart(64, "0")),
  root: treeRoot(leaves.slice(0, k + 1)).toString(16).padStart(64, "0"),
}));
fs.writeFileSync(outVectors, JSON.stringify({ hashes: vectors, merkle }, null, 2) + "\n");
console.log("poseidon([1,2]) =", vectors[3].output);
